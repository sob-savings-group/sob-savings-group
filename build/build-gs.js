/* Bundles src/core + src/backend into ONE Apps Script file (dist/Code_Ledger.gs). No bundler: each UMD module is wrapped in a
   function exposing a private `module`, and `require("./x.js")` is resolved from the table below. */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const order = ["core/dates", "core/ledger", "core/governance", "core/loans", "core/security", "core/profit", "core/cycle", "core/reconcile", "core/notify", "core/airtime", "core/history", "core/commands", "core/kpis", "core/migrate", "core/reports", "backend/store", "backend/backup", "backend/auth", "backend/api"];
let out = "/* GENERATED by build/build-gs.js — do not edit. Source of truth: src/. */\nconst __M = {};\nfunction __req(p){ const k = p.replace(/^(\\.\\.?\\/)+/, '').replace(/\\.js$/, ''); const key = Object.keys(__M).find(n => n === k || n.endsWith('/' + k)); if (!key) throw new Error('module ' + p); return __M[key]; }\n";
order.forEach((m) => {
  const src = fs.readFileSync(path.join(root, "src", m + ".js"), "utf8");
  out += "__M['" + m + "'] = (function(){ const module = {exports:{}}; const require = __req; const self = undefined;\n" + src + "\nreturn module.exports; })();\n";
});
out += fs.readFileSync(path.join(root, "src/backend/gas-entry.js"), "utf8");
fs.mkdirSync(path.join(root, "dist"), { recursive: true });
fs.writeFileSync(path.join(root, "dist/Code_Ledger.gs"), out);
console.log("built dist/Code_Ledger.gs", out.length, "bytes");
